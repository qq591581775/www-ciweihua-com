export const getGuide = (slug: string) => guides.find((guide) => guide.slug === slug)

export const formatGuideDate = (date: string) => {
  const [year, month, day] = date.split('-')
  return `${year} 年 ${Number(month)} 月 ${Number(day)} 日`
}
